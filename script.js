/* =========================================
   CARRITO
========================================= */

let cart =
    JSON.parse(
        localStorage.getItem("footballzone-cart")
    ) || [];


function formatPrice(price) {

    return price.toLocaleString("es-MX", {
        style: "currency",
        currency: "MXN"
    });

}


function updateCartCount() {

    const count =
        document.getElementById("cart-count");

    if (!count) return;

    count.textContent =
        cart.reduce(
            (total, item) =>
                total + item.quantity,
            0
        );

}


function saveCart() {

    localStorage.setItem(
        "footballzone-cart",
        JSON.stringify(cart)
    );

    updateCartCount();

}


function addToCart(id) {

    const product =
        products.find(
            product => product.id === id
        );

    if (!product) return;

    const existing =
        cart.find(
            item => item.id === id
        );

    if (existing) {

        existing.quantity++;

    } else {

        cart.push({
            ...product,
            quantity: 1
        });

    }

    saveCart();

    alert(
        "✓ " +
        product.name +
        " agregado al carrito"
    );

}


/* =========================================
   TARJETA DE PRODUCTO
========================================= */

function createProductCard(product) {

    return `

        <article class="product-card">

            <div class="product-image">

                <img
                    src="${product.image}"
                    alt="${product.brand} ${product.name}"
                    loading="lazy"
                    onerror="this.style.display='none';"
                >

            </div>

            <div class="product-info">

                <div class="product-brand">
                    ${product.brand}
                </div>

                <h3 class="product-name">
                    ${product.name}
                </h3>

                <div class="product-price">
                    ${formatPrice(product.price)}
                </div>

                <button
                    class="add-cart"
                    onclick="addToCart(${product.id})"
                >
                    AGREGAR AL CARRITO
                </button>

            </div>

        </article>

    `;

}


/* =========================================
   PRODUCTOS
========================================= */

function renderProducts(
    brand = "Todos",
    search = ""
) {

    const container =
        document.getElementById("products");

    if (!container) return;

    const filtered =
        products.filter(product => {

            const brandOK =
                brand === "Todos" ||
                product.brand === brand;

            const searchOK =
                (
                    product.name +
                    " " +
                    product.brand
                )
                .toLowerCase()
                .includes(
                    search.toLowerCase()
                );

            return brandOK && searchOK;

        });

    container.innerHTML =
        filtered
            .map(createProductCard)
            .join("");

}


/* =========================================
   DESTACADOS
========================================= */

function renderFeatured() {

    const container =
        document.getElementById(
            "featured-products"
        );

    if (!container) return;

    container.innerHTML =
        products
            .slice(0, 8)
            .map(createProductCard)
            .join("");

}


/* =========================================
   FILTROS
========================================= */

function setupFilters() {

    const buttons =
        document.querySelectorAll(".filter");

    const search =
        document.getElementById("search");

    let currentBrand = "Todos";


    buttons.forEach(button => {

        button.addEventListener(
            "click",
            () => {

                buttons.forEach(btn =>
                    btn.classList.remove("active")
                );

                button.classList.add("active");

                currentBrand =
                    button.dataset.brand;

                renderProducts(
                    currentBrand,
                    search
                        ? search.value
                        : ""
                );

            }
        );

    });


    if (search) {

        search.addEventListener(
            "input",
            () => {

                renderProducts(
                    currentBrand,
                    search.value
                );

            }
        );

    }


    const params =
        new URLSearchParams(
            window.location.search
        );

    const brand =
        params.get("marca");


    if (
        brand &&
        ["Adidas", "Nike", "PUMA"].includes(brand)
    ) {

        currentBrand = brand;

        buttons.forEach(button => {

            button.classList.remove("active");

            if (
                button.dataset.brand === brand
            ) {

                button.classList.add("active");

            }

        });

        renderProducts(
            brand,
            ""
        );

    }

}


/* =========================================
   PEDIDO
========================================= */

function renderOrder() {

    const container =
        document.getElementById(
            "order-items"
        );

    const totalElement =
        document.getElementById(
            "order-total"
        );

    if (
        !container ||
        !totalElement
    ) return;


    if (cart.length === 0) {

        container.innerHTML = `

            <p style="color:#888;">
                Tu carrito está vacío.
            </p>

            <br>

            <a
                href="productos.html"
                style="color:#b7ff00;"
            >
                VER TENIS
            </a>

        `;

        totalElement.textContent =
            formatPrice(0);

        return;

    }


    let total = 0;


    container.innerHTML =
        cart.map(item => {

            const subtotal =
                item.price *
                item.quantity;

            total += subtotal;


            return `

                <div class="order-item">

                    <div>

                        <div class="order-item-name">
                            ${item.name}
                        </div>

                        <small style="color:#777;">
                            ${item.brand}
                            · Cantidad:
                            ${item.quantity}
                        </small>

                    </div>

                    <div class="order-item-price">
                        ${formatPrice(subtotal)}
                    </div>

                </div>

            `;

        }).join("");


    totalElement.textContent =
        formatPrice(total);

}


/* =========================================
   CHECKOUT
========================================= */

function setupCheckout() {

    const form =
        document.getElementById(
            "checkout-form"
        );

    if (!form) return;


    form.addEventListener(
        "submit",
        event => {

            event.preventDefault();


            if (cart.length === 0) {

                alert(
                    "Tu carrito está vacío."
                );

                return;

            }


            const success =
                document.getElementById(
                    "success-message"
                );

            success.classList.add("show");


            cart = [];

            saveCart();

        }
    );

}


/* =========================================
   INICIO
========================================= */

document.addEventListener(
    "DOMContentLoaded",
    () => {

        updateCartCount();

        renderFeatured();

        renderProducts();

        setupFilters();

        renderOrder();

        setupCheckout();

    }
);
